			float num = float.MaxValue;
			for (int i = 0; i < Campaign.Current.AllHideouts.Count; i++)
			{
				Hideout hideout = Campaign.Current.AllHideouts[i];
				if (hideout.IsInfested)
				{
					float distance = Campaign.Current.Models.MapDistanceModel.GetDistance(hideout.Settlement, issueOwner.CurrentSettlement, false, false, MobileParty.NavigationType.Default);
					if (distance <= this.NearbyHideoutMaxRange && distance < num)
					{
						num = distance;
						settlement = hideout.Settlement;
					}
				}
			}
			return settlement;
		}

